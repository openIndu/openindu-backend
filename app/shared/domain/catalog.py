"""Catalog outcomes independent of HTTP and presentation language."""
from enum import StrEnum


class CatalogCode(StrEnum):
    SW_NOT_FOUND = "CATALOG_SW_NOT_FOUND"
    SW_VERSION_NOT_FOUND = "CATALOG_SW_VERSION_NOT_FOUND"
    SUBMISSION_NOT_FOUND = "CATALOG_SUBMISSION_NOT_FOUND"
    INVALID_BRAND = "CATALOG_INVALID_BRAND"
    INVALID_CATEGORY = "CATALOG_INVALID_CATEGORY"
    UNSUPPORTED_PACKAGE_FORMAT = "CATALOG_UNSUPPORTED_PACKAGE_FORMAT"
    FILE_TOO_LARGE = "CATALOG_FILE_TOO_LARGE"
    FILE_SIZE_INVALID = "CATALOG_FILE_SIZE_INVALID"
    DOWNLOAD_LIMIT_REACHED = "CATALOG_DOWNLOAD_LIMIT_REACHED"
    MEMBER_CANNOT_ADD_VERSION = "CATALOG_MEMBER_CANNOT_ADD_VERSION"
    UPLOAD_TARGET_NOT_FOUND = "CATALOG_UPLOAD_TARGET_NOT_FOUND"
    UPLOAD_TOKEN_INVALID = "CATALOG_UPLOAD_TOKEN_INVALID"
    UPLOAD_TOKEN_UNUSABLE = "CATALOG_UPLOAD_TOKEN_UNUSABLE"
    PARTS_MISSING = "CATALOG_PARTS_MISSING"
    MULTIPART_MERGE_FAILED = "CATALOG_MULTIPART_MERGE_FAILED"
    FILE_NOT_ON_OSS = "CATALOG_FILE_NOT_ON_OSS"
    VERSION_FILE_EXISTS = "CATALOG_VERSION_FILE_EXISTS"
    SOFTWARE_FILE_EXISTS = "CATALOG_SOFTWARE_FILE_EXISTS"
    REJECT_REASON_REQUIRED = "CATALOG_REJECT_REASON_REQUIRED"
    REJECT_PUBLISHED_BLOCKED = "CATALOG_REJECT_PUBLISHED_BLOCKED"
    INVALID_REVIEW_ACTION = "CATALOG_INVALID_REVIEW_ACTION"
    NAME_REQUIRED = "CATALOG_NAME_REQUIRED"
    NO_VERSIONS_SELECTED = "CATALOG_NO_VERSIONS_SELECTED"
    NO_SOFTWARE_SELECTED = "CATALOG_NO_SOFTWARE_SELECTED"
    DOC_NOT_FOUND = "CATALOG_DOC_NOT_FOUND"
    INVALID_SERIES = "CATALOG_INVALID_SERIES"
    DOC_UNSUPPORTED_FORMAT = "CATALOG_DOC_UNSUPPORTED_FORMAT"
    DOC_DOWNLOAD_LIMIT_REACHED = "CATALOG_DOC_DOWNLOAD_LIMIT_REACHED"
    DOC_PREVIEW_LIMIT_REACHED = "CATALOG_DOC_PREVIEW_LIMIT_REACHED"
    DOC_NAME_REQUIRED = "CATALOG_DOC_NAME_REQUIRED"
    NO_DOCUMENTS_SELECTED = "CATALOG_NO_DOCUMENTS_SELECTED"
    TAG_NOT_FOUND = "CATALOG_TAG_NOT_FOUND"
    TAG_ALREADY_EXISTS = "CATALOG_TAG_ALREADY_EXISTS"
    TAG_TYPE_INVALID = "CATALOG_TAG_TYPE_INVALID"
    TAG_VALUE_AND_LABEL_REQUIRED = "CATALOG_TAG_VALUE_AND_LABEL_REQUIRED"
    TAG_VALUE_REQUIRED = "CATALOG_TAG_VALUE_REQUIRED"
    TAG_LABEL_REQUIRED = "CATALOG_TAG_LABEL_REQUIRED"
    TAG_SERIES_PARENT_REQUIRED = "CATALOG_TAG_SERIES_PARENT_REQUIRED"
    TAG_IN_USE = "CATALOG_TAG_IN_USE"


class CatalogError(Exception):
    """Transport-independent catalog failure."""

    def __init__(self, code: CatalogCode, **params: object) -> None:
        self.code = code
        self.params = params
        super().__init__(code.value)
