"""Authentication outcomes independent of HTTP and presentation language."""

from enum import StrEnum


class BizCode(StrEnum):
    OK = "OK"
    AUTH_SMS_SENT = "AUTH_SMS_SENT"
    AUTH_LOGIN_SUCCESS = "AUTH_LOGIN_SUCCESS"
    AUTH_REGISTER_SUCCESS = "AUTH_REGISTER_SUCCESS"
    AUTH_ACCOUNT_CREATED = "AUTH_ACCOUNT_CREATED"
    AUTH_TOKEN_REFRESHED = "AUTH_TOKEN_REFRESHED"
    AUTH_PROFILE_UPDATED = "AUTH_PROFILE_UPDATED"
    AUTH_LOGGED_OUT = "AUTH_LOGGED_OUT"
    AUTH_ACCOUNT_DELETED = "AUTH_ACCOUNT_DELETED"
    AUTH_PHONE_CHANGED = "AUTH_PHONE_CHANGED"
    AUTH_INVALID_PHONE = "AUTH_INVALID_PHONE"
    AUTH_INVALID_CODE = "AUTH_INVALID_CODE"
    AUTH_USER_NOT_FOUND = "AUTH_USER_NOT_FOUND"
    AUTH_USER_EXISTS = "AUTH_USER_EXISTS"
    AUTH_PHONE_PREVIOUSLY_DELETED = "AUTH_PHONE_PREVIOUSLY_DELETED"
    AUTH_ACCOUNT_DISABLED = "AUTH_ACCOUNT_DISABLED"
    AUTH_TOKEN_ACCOUNT_DISABLED = "AUTH_TOKEN_ACCOUNT_DISABLED"
    AUTH_ACCOUNT_REMOVED = "AUTH_ACCOUNT_REMOVED"
    AUTH_PHONE_EXISTS = "AUTH_PHONE_EXISTS"
    AUTH_SLIDER_FAILED = "AUTH_SLIDER_FAILED"
    AUTH_SLIDER_REQUIRED = "AUTH_SLIDER_REQUIRED"
    AUTH_SMS_RATE_LIMIT = "AUTH_SMS_RATE_LIMIT"
    AUTH_SMS_DAILY_LIMIT = "AUTH_SMS_DAILY_LIMIT"
    AUTH_SMS_FAILED = "AUTH_SMS_FAILED"
    AUTH_TOKEN_INVALID = "AUTH_TOKEN_INVALID"
    AUTH_REFRESH_INVALID = "AUTH_REFRESH_INVALID"
    AUTH_REFRESH_REVOKED = "AUTH_REFRESH_REVOKED"
    AUTH_ACCOUNT_UNAVAILABLE = "AUTH_ACCOUNT_UNAVAILABLE"
    AUTH_TOKEN_REVOKED = "AUTH_TOKEN_REVOKED"
    AUTH_FORCED_LOGOUT = "AUTH_FORCED_LOGOUT"


class AuthError(Exception):
    """Transport-independent authentication failure."""

    def __init__(self, code: BizCode, **params: object) -> None:
        self.code = code
        self.params = params
        super().__init__(code.value)
